    private static func gcd(_ a0: Int, _ b0: Int) -> Int {
        var a = a0, b = b0
        while true {
            a = a % b
            if a == 0 { return b }
            b = b % a
            if b == 0 { return a }
        }
    }

    private static func lcm(_ a: Int, _ b: Int) -> Int {
        if a == 0 || b == 0 { return 1 }
        return (a * b) / gcd(a, b)
    }

    private static func generateKey(firewireID: [UInt8]) -> [UInt8] {
        var y = [UInt8](repeating: 0, count: 16)
        for i in 0..<4 {
            let a = Int(firewireID[i * 2])
            let b = Int(firewireID[i * 2 + 1])
            let l = lcm(a, b)
            let hi = UInt8((l & 0xFF00) >> 8)
            let lo = UInt8(l & 0xFF)
            y[i * 4] = table1[Int(hi)]
            y[i * 4 + 1] = table2[Int(hi)]
            y[i * 4 + 2] = table1[Int(lo)]
            y[i * 4 + 3] = table2[Int(lo)]
        }
        var sha = Insecure.SHA1()
        sha.update(data: fixed)
        sha.update(data: y)
        let digest = Array(sha.finalize())
        var key = [UInt8](repeating: 0, count: 64)
        for (i, b) in digest.enumerated() { key[i] = b }
        return key
    }

    /// HMAC-SHA1 style checksum over the database bytes with a key derived from the FireWire id.
    static func compute(firewireID: [UInt8], database: [UInt8]) -> [UInt8] {
        var key = generateKey(firewireID: firewireID)
        for i in 0..<64 { key[i] ^= 0x36 }
        var inner = Insecure.SHA1()
        inner.update(data: key)
        inner.update(data: database)
        let innerDigest = Array(inner.finalize())
        for i in 0..<64 { key[i] ^= 0x36 ^ 0x5C }
        var outer = Insecure.SHA1()
        outer.update(data: key)
        outer.update(data: innerDigest)
        return Array(outer.finalize())
    }

    /// Parses a FireWire GUID hex string (16 hex digits) into 8 bytes (zero-padded to 20 as libgpod does).
    static func firewireBytes(from hex: String) -> [UInt8]? {
        var clean = hex.trimmingCharacters(in: .whitespacesAndNewlines)
        if clean.hasPrefix("0x") || clean.hasPrefix("0X") { clean.removeFirst(2) }
        guard clean.count >= 16, clean.count % 2 == 0 else { return nil }
        var bytes: [UInt8] = []
        var idx = clean.startIndex
        while idx < clean.endIndex {
            let next = clean.index(idx, offsetBy: 2)
            guard let b = UInt8(clean[idx..<next], radix: 16) else { return nil }
            bytes.append(b)
            idx = next
        }
        while bytes.count < 20 { bytes.append(0) }
        return bytes
    }

    /// Signs an in-memory iTunesDB (mhbd at offset 0). Mirrors itdb_hash58_write_hash.
    static func sign(database: inout [UInt8], firewireID: [UInt8]) throws {
        guard database.count >= 0x6C else { throw IPodDBError.corrupt("database too small to sign") }
        let backupDBID = Array(database[0x18..<0x20])
        let backup32 = Array(database[0x32..<0x46])
        for i in 0x18..<0x20 { database[i] = 0 }
        for i in 0x32..<0x46 { database[i] = 0 }
        for i in 0x58..<0x6C { database[i] = 0 }
        database[0x30] = 1 // hashing scheme = hash58
        database[0x31] = 0
        let checksum = compute(firewireID: firewireID, database: database)
        for (i, b) in checksum.enumerated() { database[0x58 + i] = b }
        for (i, b) in backupDBID.enumerated() { database[0x18 + i] = b }
        for (i, b) in backup32.enumerated() { database[0x32 + i] = b }
    }
